// Render NEGATIVE-CONTROLS.md from a run.sh output directory (reads only files run.sh wrote).
// Usage: node table.mjs <outDir>
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
const dir = process.argv[2];
const res = Object.fromEntries(readFileSync(join(dir, 'results.tsv'), 'utf8').trim().split('\n').slice(1)
  .map((l) => l.split('\t')).map(([n, c, v]) => [n, { c, v }]));
const jsonl = (n) => readFileSync(join(dir, `${n}.jsonl`), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const vjson = (n) => (existsSync(join(dir, `${n}.validator.json`)) ? JSON.parse(readFileSync(join(dir, `${n}.validator.json`), 'utf8')) : null);
function newRow(name, label, expect) {
  const L = jsonl(name);
  const end = L[L.length - 1];
  const att = L.filter((r) => r.kind === 'attempt');
  const verdicts = att.map((r) => `${r.arm}: ${r.verdict}${r.failingCheck ? ` (\`${r.failingCheck}\`)` : ''}${r.stoppedBy ? ` — stopped by \`${r.stoppedBy.reason}\` on \`${(r.stoppedBy.detail?.diff ?? []).join(',')}\`` : ''}`).join('<br>');
  const cons = att.filter((r) => r.conservation?.evaluated).map((r) => `${r.arm} ${r.conservation.ok ? 'OK' : 'FAIL'} (${r.conservation.checks.length} checks)`).join(', ') || '—';
  const v = vjson(name);
  return `| ${label} | ${expect} | ${verdicts} | ${cons} | \`${end.stop.reason}\` / exit **${res[name].c}** | exit **${res[name].v}** (${v?.consistent ? 'consistent' : 'INCONSISTENT'}${v?.accepted ? ', accepted' : ', not accepted'}) |`;
}
function oldCell(name) {
  const rows = JSON.parse(readFileSync(join(dir, `${name}.recheck.json`), 'utf8'));
  return rows.map((r) => `${r.paymasterKind}: old row \`status=${r.oldRecorded.status}, infraFailure=${r.oldRecorded.infraFailure}, sponsorshipFailed=${r.oldRecorded.sponsorshipFailed}\` → counted as success; actual UserOperationEvent for the recorded hash: ${r.userOpEventForRecordedHash ? `success=${r.userOpEventForRecordedHash.success}` : '**none**'}`).join('<br>');
}
const vInj = vjson('e-conservation-injected');
const vMiss = vjson('e-missing-field');
const out = [];
out.push('# A6 gauge — fixture negative controls (local Anvil only; NOT A6 data)', '');
out.push('Generated by `script/a6-collector/negative-controls/table.mjs` from the files in this directory.', '');
out.push('## New gauge (this branch)', '');
out.push('| control | expected | per-attempt verdict (failing check) | conservation | collector stop / exit | validator |');
out.push('|---|---|---|---|---|---|');
out.push(newRow('positive', 'positive: real triplet', 'all USEROP_SUCCESS, SP conservation OK, exit 0'));
out.push(newRow('a-exec-revert', '(a) tx OK, op execution reverts', 'USEROP_REVERTED, not success'));
out.push(newRow('b-drop-op', '(b) tx OK, our op not in bundle', 'NO_EVENT'));
out.push(newRow('c-wrong-hash', '(c) wrong expected userOpHash', 'failure row (HASH_MISMATCH)'));
out.push(newRow('d-tamper-b', '(d) endpoint B tampers a read-back', 'stop non-zero (RPC_DISAGREEMENT, 20)'));
out.push(`| (e) fake delta injected into validator input | validator fails | — | — | — | exit **${res['e-conservation-injected'].v}**: ${(vInj?.errors ?? []).map((e) => `\`${e}\``).join('<br>')} |`);
out.push(`| (e') required field deleted | validator fails closed | — | — | — | exit **${res['e-missing-field'].v}**: \`${vMiss?.missing ?? vMiss?.crash}\` |`);
out.push('', 'Collector exit 10 = attempt budget exhausted before N matched triplets (expected for a one-attempt fixture run: a fixture row never counts toward N). Validator exit 3 = recomputation agrees with the record but the run is not accepted; 1 = recomputation disagrees / conservation fails; 2 = missing field (fail closed); 0 = consistent and accepted.', '');
out.push('## Old collector (`origin/feat/aoa-balance-mode-5.5.0`) on the same fixtures', '');
out.push(`Old collector source: \`${readFileSync(join(dir, 'old-collector.ref'), 'utf8').trim()}\`; fixture patch: \`old-collector.fixture.diff\` (changes only what is bundled, not how the row is judged).`, '');
out.push('| control | old collector exit | what the old collector recorded vs. what the receipt says |', '|---|---|---|');
out.push(`| (a) exec revert | ${res['old-a-exec-revert'].c} | ${oldCell('old-a-exec-revert')} |`);
out.push(`| (b) dropped op | ${res['old-b-drop-op'].c} | ${oldCell('old-b-drop-op')} |`);
const n50 = vjson('n50-mechanism');
const L50 = jsonl('n50-mechanism');
const end50 = L50[L50.length - 1];
out.push('', '## N=50 mechanism run', '');
out.push(`collector: stop \`${end50.stop.reason}\`, exit ${res['n50-mechanism'].c}, matched triplets ${end50.matchedTriplets}/${end50.targetTriplets}, tally \`${JSON.stringify(end50.tally)}\``);
out.push(`validator: exit ${res['n50-mechanism'].v}, consistent=${n50?.consistent}, accepted=${n50?.accepted}, recomputed \`${JSON.stringify(n50?.recomputed)}\`, matchedTriplets=${n50?.matchedTriplets}`);
console.log(out.join('\n'));
