// Produce a fixture-injecting copy of the PREVIOUS collector (the one this gauge replaces), to show
// how it records negative controls (a) and (b). The patch only changes WHAT is bundled — the old
// collector's own verdict logic (receipt.status === 'success' → success row) is left byte-identical.
//
// Usage: node patch-old-collector.mjs <old-collector.mjs> <out.mjs>
//   then run <out.mjs> with OLD_FIXTURE=exec-revert OLD_FIXTURE_CALLDATA=0x… or OLD_FIXTURE=drop-op.
import { readFileSync, writeFileSync } from 'node:fs';
const [src, dst] = process.argv.slice(2);
let s = readFileSync(src, 'utf8');
function rep(a, b) { if (!s.includes(a)) { console.error(`anchor not found: ${a}`); process.exit(1); } s = s.replace(a, b); }
// (a) every op's callData comes from the environment (a reverting SimpleAccount.execute).
rep("async function buildOp(ctxArg, { sender, nonce, callData = '0x',",
    "async function buildOp(ctxArg, { sender, nonce, callData = (process.env.OLD_FIXTURE_CALLDATA ?? '0x'),");
// (b) bundle a DIFFERENT op of the same sender (nonce key 1) instead of the op whose hash is recorded.
rep("  const { packed, hash } = await build({ sender: senderAddr, nonce });",
    "  const { packed, hash } = await build({ sender: senderAddr, nonce });\n" +
    "  const sendOp = process.env.OLD_FIXTURE === 'drop-op'\n" +
    "    ? (await build({ sender: senderAddr, nonce: await ctx.pub.readContract({ address: EP, abi: EP_ABI, functionName: 'getNonce', args: [senderAddr, 1n] }) })).packed\n" +
    "    : packed;");
rep('const preflight = await simulateRevert(packed, undefined);', 'const preflight = await simulateRevert(sendOp, undefined);');
rep("functionName: 'handleOps', args: [[packed], ctx.account.address], chain: null,", "functionName: 'handleOps', args: [[sendOp], ctx.account.address], chain: null,");
writeFileSync(dst, `// GENERATED by negative-controls/patch-old-collector.mjs from ${src} — do not commit.\n` + s);
