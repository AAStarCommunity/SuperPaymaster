#!/usr/bin/env python3
"""R2-F4: per-value delta (new - old) of every R2A|key|value row present in both log dirs (same test file,
same key, same print index). Rows are split by unit by magnitude: |value| < 1e11 in both runs = gas units;
otherwise wei / 1e18-scaled token units (not gas). Gas rows are further split into measured rows and
derived rows (key contains 'minus', 'band_width', 'delta' or 'diff': a difference of two measurements).
Usage: python3 -I delta_g.py <old logs dir> <new logs dir> <out.md>"""
import re, sys, os
from collections import OrderedDict

old_dir, new_dir, out = sys.argv[1:4]
row = re.compile(r"R2A\|([^|]+)\|(-?\d+)")

def rows(p):
    d = OrderedDict()
    for line in open(p, encoding="utf-8", errors="replace"):
        m = row.search(line)
        if m:
            d.setdefault(m.group(1), []).append(int(m.group(2)))
    return d

vals = []
for f in sorted(os.listdir(new_dir)):
    if not f.endswith("_amsterdam.log") or not os.path.exists(os.path.join(old_dir, f)):
        continue
    o, n = rows(os.path.join(old_dir, f)), rows(os.path.join(new_dir, f))
    for k in n:
        for i, (a, b) in enumerate(zip(o.get(k, []), n[k])):
            vals.append((f, k, i, a, b, b - a))

def cls(v):
    if abs(v[3]) >= 10**11 or abs(v[4]) >= 10**11:
        return "non-gas (wei / 1e18 token units)"
    k = v[1].lower()
    return "gas, derived (difference of two measurements)" if any(s in k for s in ("minus", "band_width", "delta", "diff")) else "gas, measured"

L = [f"# Per-value deltas, new − old\n\nold = `{old_dir}`, new = `{new_dir}`; generated by `scripts/delta_g.py`.\n",
     "| class | values | up | down | zero | most negative | least negative | smallest positive | largest positive |",
     "|---|---|---|---|---|---|---|---|---|"]
detail = []
for c in ("gas, measured", "gas, derived (difference of two measurements)", "non-gas (wei / 1e18 token units)"):
    r = [v for v in vals if cls(v) == c]
    up = sorted([v for v in r if v[5] > 0], key=lambda v: v[5]); dn = sorted([v for v in r if v[5] < 0], key=lambda v: v[5])
    z = [v for v in r if v[5] == 0]
    fmt = lambda v: f"{v[5]:+,} (`{v[1]}`)" if v else "—"
    L.append(f"| {c} | {len(r)} | {len(up)} | {len(dn)} | {len(z)} | {fmt(dn[0] if dn else None)} | {fmt(dn[-1] if dn else None)} | {fmt(up[0] if up else None)} | {fmt(up[-1] if up else None)} |")
    if c.startswith("gas"):
        for v in up + dn:
            detail.append(f"| {c.split(',')[1].strip().split(' ')[0]} | {v[0]} | `{v[1]}` | {v[2]} | {v[3]:,} | {v[4]:,} | {v[5]:+,} |")
L.append("\nAll non-zero gas-unit deltas (measured and derived):\n")
L.append("| class | test | key | idx | old | new | Δ |\n|---|---|---|---|---|---|---|")
L += sorted(detail, key=lambda s: int(s.rsplit("|", 2)[1].replace(",", "")))
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(L[:6]))
